let stepN = 0;
function emitCall(method: string, path: string, body: any | null, comment: string, captureVar?: string): void {
  stepN++;
  const env: any = { method, path };
  if (body !== null) env.body = body;
  const tag = `__SEM_${stepN}__`;
  out(`# step ${stepN}: ${comment}`);
  out(`log "[${stepN}] ${comment}"`);
  if (captureVar) {
    out(`${captureVar}=$($SEM <<'${tag}'`);
  } else {
    out(`$SEM <<'${tag}' > /dev/null`);
  }
  out(JSON.stringify(env));
  out(tag);
  if (captureVar) out(")");
  out("");
}

// Helper to emit a "skip-if-exists" idempotent insert.
function emitIdempotentInsert(path: string, row: any, existsCheckJq: string, comment: string): void {
  out(`if [ "$(echo "$EXISTING" | jq -r '${existsCheckJq}')" = "false" ]; then`);
  emitCall("POST", path, [row], comment);
  out("else");
  out(`  log "[skip] ${comment} already present"`);
  out("fi");
  out("");
}


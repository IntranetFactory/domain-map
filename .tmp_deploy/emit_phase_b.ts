// Replace `D_KNOWN.foo` references with the actual literal id at emit time.
function resolveDexpr(expr: string): string {
  if (expr.startsWith("D_KNOWN.")) {
    const key = expr.slice("D_KNOWN.".length) as keyof typeof D_KNOWN;
    return String(D_KNOWN[key]);
  }
  return expr; // bash variable reference (e.g., COMPETENCY_MODELS_ID)
}


#!/usr/bin/env bun
// Removes every British spelling from every in-scope text file of both repos, as the project owner asked on 2026-11-03.
// Spelling only. The detection and the allow-list are fixBritishInFile in scripts/lib/british_spelling.ts, the same code
// the terminology tests use to keep British spellings out.
//
// Dry-run by default; --apply writes. Line endings are kept. Every YAML and JSON file touched is parsed before and
// after: a YAML or JSON file is written only if it parses both ways and its keys are unchanged. Symlinks are not
// followed, so `.claude/skills/semantius-*` (links into `.agents/skills/` or `semantius-plugin/`) are never edited
// through the link.
import { lstatSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { extname, join } from "node:path";
import { fixBritishInFile } from "../scripts/lib/british_spelling";

const APPLY = process.argv.includes("--apply");
const FILE_LIST = process.argv.includes("--files");
const DM = "C:/dev/domain-map", SA = "C:/dev/semantius-agent";
const NEVER = new Set(["node_modules", ".git", ".next", "dist"]);
const TEXT = new Set([".md", ".mdx", ".ts", ".tsx", ".js", ".mjs", ".cjs", ".json", ".yaml", ".yml", ".csv", ".tsv", ".txt", ".html", ".toml", ".sql", ".sh", ".py"]);

const walk = (dir: string): string[] =>
  readdirSync(dir).flatMap((n) => {
    if (NEVER.has(n)) return [];
    const p = join(dir, n).replace(/\\/g, "/");
    const st = lstatSync(p);
    if (st.isSymbolicLink()) return [];
    return st.isDirectory() ? walk(p) : [p];
  });

// Excluded because they must stay exact: counted below, never written.
const EXCLUDED: [string, RegExp][] = [
  ["DM backups/", /^DM:backups\//],
  ["DM .cache/", /^DM:\.cache\//],
  ["DM crud*.log", /^DM:crud.*\.log$/],
  ["DM domain_map*.json", /^DM:domain_map.*\.json$/],
  ["DM plans/snapshots/*.json", /^DM:plans\/snapshots\/.*\.json$/],
  ["DM .tmp_deploy/", /^DM:(.*\/)?\.tmp_deploy\//],
  ["DM .agents/skills/", /^DM:\.agents\/skills\//],
  ["DM .claude/skills/llm-wiki/", /^DM:\.claude\/skills\/llm-wiki\//],
  ["SA raw/", /^SA:raw\//],
  ["SA sources/", /^SA:sources\//],
  ["SA roundtrip-analysis/", /^SA:roundtrip-analysis\//],
  ["SA .tmp_admin/", /^SA:\.tmp_admin\//],
  ["SA .tmp_deploy/", /^SA:\.tmp_deploy\//],
  ["SA .tmp_import/", /^SA:\.tmp_import\//],
  ["SA .agents/skills/", /^SA:\.agents\/skills\//],
  ["SA .claude/skills/llm-wiki/", /^SA:\.claude\/skills\/llm-wiki\//],
  ["SA .claude/worktrees/", /^SA:\.claude\/worktrees\//],
  ["SA crud*.log", /^SA:crud.*\.log$/],
];
// In scope, but stays on the allow-list. Reasons are in the final report.
const KEPT: [string, RegExp][] = [
  ["the two CLAUDE.md files (may not be edited)", /(^|\/)CLAUDE\.md$/],
  ["harness configuration (.claude/settings*.json, not ours to change)", /^(DM|SA):\.claude\/settings/],
  ["the word map itself", /^DM:scripts\/lib\/british_spelling\.ts$|^SA:scripts\/british_spelling\.ts$/],
  ["tests that use British words on purpose", /^DM:scripts\/lib\/__tests__\/(health_b|catalog_invariants|british_spelling|terminology)\.test\.ts$|^SA:scripts\/terminology\.test\.ts$/],
  ["Lucide's icon tags: third-party search terms, regenerated by scripts/update-lucide-icon-tags.ts", /lucide-icon-tags\.json$/],
  ["vendored payload of a past run", /^SA:\.email-payload\.json$/],
  ["a raw scrape of a third-party web page", /^DM:tmpmonday_templates\.html$/],
];

type Area = { files: number; words: number };
const areas = new Map<string, Area>();
const wordCount = new Map<string, number>();
const excludedCount = new Map<string, { files: number; hits: number }>();
const keptCount = new Map<string, { files: number; hits: number }>();
const edits: { file: string; before: string; after: string }[] = [];
const problems: string[] = [];
let scanned = 0;

const keysOf = (node: any, out: string[] = []): string[] => {
  if (Array.isArray(node)) node.forEach((n) => keysOf(n, out));
  else if (node && typeof node === "object") for (const [k, v] of Object.entries(node)) {
    out.push(k);
    keysOf(v, out);
  }
  return out;
};
const parse = (f: string, text: string) => (f.toLowerCase().endsWith(".json") ? JSON.parse(text) : (Bun as any).YAML.parse(text));

for (const [repo, root] of [["DM", DM], ["SA", SA]] as const) {
  for (const full of walk(root)) {
    const rel = full.slice(root.length + 1);
    const tag = `${repo}:${rel}`;
    const e = extname(rel).toLowerCase();
    if (!TEXT.has(e) && !/\.log$/.test(rel)) continue;
    const excluded = EXCLUDED.find(([, re]) => re.test(tag));
    const kept = KEPT.find(([, re]) => re.test(tag) || re.test(rel));
    const buf = readFileSync(full);
    if (buf.includes(0)) continue;
    const before = buf.toString("utf8");
    if (Buffer.compare(Buffer.from(before, "utf8"), buf) !== 0) {
      problems.push(`${tag}: not valid UTF-8, left alone`);
      continue;
    }
    const { fixed, hits } = fixBritishInFile(before);
    if (excluded || kept) {
      const store = excluded ? excludedCount : keptCount;
      const name = (excluded ?? kept)![0];
      const c = store.get(name) ?? { files: 0, hits: 0 };
      c.files++;
      c.hits += hits.length;
      store.set(name, c);
      continue;
    }
    scanned++;
    if (!hits.length) continue;
    if (/\.(ya?ml|json)$/i.test(rel)) {
      try {
        const a = keysOf(parse(rel, before)), b = keysOf(parse(rel, fixed));
        if (a.join("\u0000") !== b.join("\u0000")) {
          problems.push(`${tag}: the edit would change a key, left alone: ${hits.join(", ")}`);
          continue;
        }
      } catch (err) {
        problems.push(`${tag}: does not parse before or after the edit, left alone: ${(err as Error).message.split("\n")[0]}`);
        continue;
      }
    }
    edits.push({ file: full, before, after: fixed });
    const area = repo === "SA" ? `semantius-agent/${rel.includes("/") ? rel.split("/")[0] : "root docs"}` : rel.includes("/") ? (rel.startsWith(".claude") ? ".claude/skills" : rel.split("/")[0]) : "root docs";
    const cur = areas.get(area) ?? { files: 0, words: 0 };
    cur.files++;
    cur.words += hits.length;
    areas.set(area, cur);
    for (const h of hits) {
      const k = h.toLowerCase();
      wordCount.set(k, (wordCount.get(k) ?? 0) + 1);
    }
    if (FILE_LIST) console.log(`${String(hits.length).padStart(4)} ${tag}`);
  }
}

console.log(`${scanned} in-scope text files scanned; ${edits.length} to change.`);
console.log(`Per area:\n${[...areas].sort().map(([a, v]) => `  ${a}: ${v.files} files, ${v.words} words`).join("\n")}`);
console.log(`Words (${[...wordCount.values()].reduce((a, b) => a + b, 0)}):\n  ${[...wordCount].sort((a, b) => b[1] - a[1]).map(([w, n]) => `${w} ${n}`).join(", ")}`);
console.log(`\nExcluded, must stay exact (counts only):\n${[...excludedCount].map(([k, v]) => `  ${k}: ${v.hits} hits in ${v.files} files`).join("\n")}`);
console.log(`\nKept on the allow-list:\n${[...keptCount].map(([k, v]) => `  ${k}: ${v.hits} hits in ${v.files} files`).join("\n")}`);
if (problems.length) console.error(`\n${problems.length} problems:\n${problems.join("\n")}`);
if (!APPLY) {
  console.log("\nNo writes (dry-run).");
  process.exit(0);
}
for (const e of edits) writeFileSync(e.file, e.after);
console.log(`\nwrote ${edits.length} files`);

// --- B1-S1 ------------------------------------------------------------------
const B1_S1_NEW_BUSINESS_LOGIC =
  "Endpoint-agent runtime, synthetic transaction generation, and correlation across user / device / app / network signals: code-dominant data plane.";

async function applyB1S1() {
  console.log("\n=== B1-S1: strip em-dash from domains.id=83 business_logic ===");
  const before = await get(
    `/domains?id=eq.${DEM_DOMAIN_ID}&select=id,domain_code,business_logic`,
  );
  if (before.length !== 1) {
    throw new Error(`pre-flight: expected DEM domain id=${DEM_DOMAIN_ID}, got ${before.length}`);
  }
  const current = String(before[0].business_logic ?? "");
  if (!current.includes("—")) {
    console.log("  = no em-dash present, skipping PATCH");
    return;
  }
  if (B1_S1_NEW_BUSINESS_LOGIC.includes("—")) {
    throw new Error("safety: replacement text still contains em-dash");
  }
  await patch(`/domains?id=eq.${DEM_DOMAIN_ID}`, {
    business_logic: B1_S1_NEW_BUSINESS_LOGIC,
  });
  const after = await get(
    `/domains?id=eq.${DEM_DOMAIN_ID}&select=business_logic`,
  );
  if (String(after[0].business_logic ?? "").includes("—")) {
    throw new Error("post-flight: em-dash still present after PATCH");
  }
  console.log("  + PATCH applied; em-dash removed");
}

// --- B1-B7 ------------------------------------------------------------------
// Rule #10 users-edges; audit pre-specifies the three edges.
type UsersEdge = {
  related_do_id: number;
  verb: string;
  inverse: string;
  label: string;
};
const B1_B7_EDGES: UsersEdge[] = [
  {
    related_do_id: DO.endpoint_experience_scores,
    verb: "observes",
    inverse: "is observed by",
    label: "users observes endpoint_experience_scores",
  },
  {
    related_do_id: DO.real_user_sessions,
    verb: "generates",
    inverse: "is generated by",
    label: "users generates real_user_sessions",
  },
  {
    related_do_id: DO.digital_friction_events,
    verb: "experiences",
    inverse: "is experienced by",
    label: "users experiences digital_friction_events",
  },
];

async function applyB1B7() {
  console.log("\n=== B1-B7: 3 users-edges into data_object_relationships ===");
  const existing = await get(
    `/data_object_relationships?data_object_id=eq.${USERS_DO_ID}` +
      `&related_data_object_id=in.(${B1_B7_EDGES.map((e) => e.related_do_id).join(",")})` +
      `&select=id,data_object_id,related_data_object_id,relationship_verb`,
  );
  const existingPairs = new Set(
    existing.map((r: any) => `${r.data_object_id}.${r.related_data_object_id}`),
  );
  const toInsert: Row[] = [];
  for (const e of B1_B7_EDGES) {
    const key = `${USERS_DO_ID}.${e.related_do_id}`;
    if (existingPairs.has(key)) {
      console.log(`  = ${e.label}: already exists, skipping`);
      continue;
    }
    toInsert.push({
      data_object_relationship_label: e.label,
      data_object_id: USERS_DO_ID,
      related_data_object_id: e.related_do_id,
      relationship_verb: e.verb,
      inverse_verb: e.inverse,
      relationship_type: "one_to_many",
      relationship_kind: "association",
      owner_side: "target",
      is_required: false,
    });
  }
  if (toInsert.length === 0) {
    console.log("  = all 3 edges already present");
    return;
  }
  const inserted = await post("/data_object_relationships", toInsert);
  console.log(`  + inserted ${inserted.length} edge(s)`);
}


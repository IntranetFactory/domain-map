// --- B1-H1 ------------------------------------------------------------------
// Pre-specified pairs from audit B1-H1 table. PCF process ids verified to
// exist live (1299 'Triage IT service delivery incidents', 295 'Operate IT
// user support', 1137 'Select, deploy, and operate IT performance analytics
// tools'). proposal_source = 'agent_curated' per the H1 instruction.
type HpSpec = { handoff_id: number; process_id: number; note: string };
const B1_H1_PAIRS: HpSpec[] = [
  { handoff_id: HANDOFF.h664, process_id: PCF.p1299, note: "664 DEM->ITSM" },
  { handoff_id: HANDOFF.h665, process_id: PCF.p295, note: "665 DEM->AIOPS" },
  { handoff_id: HANDOFF.h666, process_id: PCF.p1137, note: "666 DEM->OBS" },
  { handoff_id: HANDOFF.h667, process_id: PCF.p295, note: "667 DEM->AIOPS RUM" },
  { handoff_id: HANDOFF.h653, process_id: PCF.p1137, note: "653 NPMD->DEM inbound" },
];

async function applyB1H1() {
  console.log("\n=== B1-H1: 5 handoff_processes pairs (APQC tagging) ===");
  // Verify processes exist
  const procIds = Array.from(new Set(B1_H1_PAIRS.map((p) => p.process_id)));
  const procs = await get(`/processes?id=in.(${procIds.join(",")})&select=id`);
  const procSet = new Set(procs.map((r: any) => Number(r.id)));
  for (const p of B1_H1_PAIRS) {
    if (!procSet.has(p.process_id))
      throw new Error(`pre-flight: process id=${p.process_id} not found`);
  }
  // Verify handoffs exist
  const handoffIds = Array.from(new Set(B1_H1_PAIRS.map((p) => p.handoff_id)));
  const hs = await get(`/handoffs?id=in.(${handoffIds.join(",")})&select=id`);
  const hsSet = new Set(hs.map((r: any) => Number(r.id)));
  for (const p of B1_H1_PAIRS) {
    if (!hsSet.has(p.handoff_id))
      throw new Error(`pre-flight: handoff id=${p.handoff_id} not found`);
  }
  // Existing pairs
  const existing = await get(
    `/handoff_processes?handoff_id=in.(${handoffIds.join(",")})` +
      `&select=id,handoff_id,process_id`,
  );
  const existingPairs = new Set(
    existing.map((r: any) => `${r.handoff_id}.${r.process_id}`),
  );
  const toInsert: Row[] = [];
  for (const p of B1_H1_PAIRS) {
    const key = `${p.handoff_id}.${p.process_id}`;
    if (existingPairs.has(key)) {
      console.log(`  = ${p.note} (${key}): already exists, skipping`);
      continue;
    }
    toInsert.push({
      handoff_id: p.handoff_id,
      process_id: p.process_id,
      role: "implements",
      proposal_source: "agent_curated",
    });
  }
  if (toInsert.length === 0) {
    console.log("  = all 5 pairs already present");
    return;
  }
  const inserted = await post("/handoff_processes", toInsert);
  console.log(`  + inserted ${inserted.length} handoff_process row(s)`);
}


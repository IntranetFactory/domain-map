// scripts/lib/health/record.ts
//
// The `checks:` block that `domain_health.ts --record` writes into audits/<CODE>/state.yaml.
//
// The block is spliced in as TEXT, never via a YAML round-trip: only the region from a top-level
// `checks:` line up to (not including) the next line that starts at column 0 (the next top-level
// key, a column-0 comment, a document marker) is replaced, minus trailing blank lines. Every other
// byte of the file, comments included, survives unchanged. When there is no `checks:` key the
// block is appended at the end of the file.
//
// Shape (flow-style result items, so line-based tools that scan for `- id: <X>` item headers, e.g.
// b9d_resolver.ts --migrate-legacy, never mistake a check result for a backlog item):
//
//   checks:
//     # generated by scripts/analytics/domain_health.ts --record; do not hand-edit
//     checklist_version: 1
//     run_at: "2026-11-01T12:00:00.000Z"
//     results:
//       - {id: B7b, result: fail, rows: [822, 823]}

import yaml from "js-yaml";
import type { Result } from "./types.ts";

export type CheckRecord = { id: string; result: Result; rows: (number | string)[] };

export const CHECKS_KEY_RE = /^checks[ \t]*:/;

function scalar(v: number | string): string {
  return typeof v === "number" && Number.isFinite(v) ? String(v) : JSON.stringify(String(v));
}

export function renderChecksBlock(checklistVersion: number, runAt: string, results: CheckRecord[]): string[] {
  const lines = [
    "checks:",
    "  # generated by scripts/analytics/domain_health.ts --record; do not hand-edit",
    `  checklist_version: ${checklistVersion}`,
    `  run_at: ${JSON.stringify(runAt)}`,
  ];
  if (results.length === 0) {
    lines.push("  results: []");
    return lines;
  }
  lines.push("  results:");
  for (const r of results) {
    if (!/^[A-Za-z][A-Za-z0-9]*$/.test(r.id)) throw new Error(`renderChecksBlock: unexpected check id ${JSON.stringify(r.id)}`);
    lines.push(`    - {id: ${r.id}, result: ${r.result}, rows: [${r.rows.map(scalar).join(", ")}]}`);
  }
  return lines;
}

type Span = { start: number; end: number; next: number }; // [start, end) = line text; next = after terminator

function lineSpans(text: string): Span[] {
  const spans: Span[] = [];
  let i = 0;
  while (i < text.length) {
    let j = i;
    while (j < text.length && text[j] !== "\n" && text[j] !== "\r") j++;
    let next = j;
    if (text[next] === "\r" && text[next + 1] === "\n") next += 2;
    else if (next < text.length) next += 1;
    spans.push({ start: i, end: j, next });
    i = next;
  }
  return spans;
}

export function detectEol(text: string): string {
  const m = text.match(/\r\n|\n|\r/);
  return m ? m[0] : "\n";
}

// Replace (or append) the `checks:` block. `blockLines` come from renderChecksBlock.
export function spliceChecksBlock(text: string, blockLines: string[]): string {
  const eol = detectEol(text);
  const block = blockLines.join(eol) + eol;
  const spans = lineSpans(text);
  const at = spans.findIndex((s) => CHECKS_KEY_RE.test(text.slice(s.start, s.end)));
  if (at < 0) {
    let head = text;
    if (head.length > 0 && !/[\r\n]$/.test(head)) head += eol;
    // One blank separator line before the block, unless the file already ends with one.
    const endsBlank = head.length === 0 || /(\r\n|\n|\r)[ \t]*(\r\n|\n|\r)$/.test(head);
    return head + (endsBlank ? "" : eol) + block;
  }
  let last = at;
  for (let k = at + 1; k < spans.length; k++) {
    const line = text.slice(spans[k].start, spans[k].end);
    if (/^\S/.test(line)) break; // column 0: next top-level key, comment or marker
    if (line.trim() !== "") last = k;
  }
  return text.slice(0, spans[at].start) + block + text.slice(spans[last].next);
}

// Parse a state.yaml text; null when it does not parse.
export function parseStateYaml(text: string): any | null {
  try {
    return yaml.load(text) ?? {};
  } catch {
    return null;
  }
}

export function recordedChecklistVersion(text: string): number | null {
  const doc = parseStateYaml(text);
  const v = doc?.checks?.checklist_version;
  return typeof v === "number" ? v : null;
}

// Guard used before any write: the spliced text must still parse, every non-`checks` key must be
// deep-equal to the original's, and the new block must read back exactly as written.
export function verifySplice(before: string, after: string, expected: { checklistVersion: number; results: CheckRecord[] }): string | null {
  const a = parseStateYaml(before);
  const b = parseStateYaml(after);
  if (a === null) return "original state.yaml does not parse as YAML; refusing to splice";
  if (b === null) return "spliced state.yaml does not parse as YAML";
  const strip = (d: any) => {
    const { checks: _c, ...rest } = d ?? {};
    return JSON.stringify(rest);
  };
  if (strip(a) !== strip(b)) return "splice changed content outside the checks: block";
  if (b.checks?.checklist_version !== expected.checklistVersion) return "spliced checks.checklist_version does not read back";
  const got = JSON.stringify(b.checks?.results ?? []);
  const want = JSON.stringify(expected.results.map((r) => ({ id: r.id, result: r.result, rows: r.rows })));
  if (got !== want) return "spliced checks.results do not read back as written";
  return null;
}
